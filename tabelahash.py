# Tabela hash é uma estrutura de dados que associa chaves a valores
# A função hash é usada para calcular um índice a partir da chave, onde o valor correspondente será armazenado
# A função hash deve ser rápida e distribuir as chaves de maneira uniforme para evitar colisões


